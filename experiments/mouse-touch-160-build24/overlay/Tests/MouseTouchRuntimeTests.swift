        try await assertJS(view, "(()=>{mouseTestRawTraces=[]; mouseTestSend('pointerdown'); mouseTestSend('pointerup'); return mouseTestEvents.filter(e=>e.type==='pointerdown').length===1 && !mouseTestEvents.some(e=>e.type==='pointerup');})()")
