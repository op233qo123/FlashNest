        try XCTUnwrap(Data(base64Encoded: fixture)).write(to: movie)
        let library = root.appendingPathComponent("library")
        let package = try PackageImporter(root: library).stageAndCommit(movie)
        defer { UserDefaults.standard.removeObject(forKey: TouchControlSettings.preferenceKey(for: package.id)) }
        XCTAssertFalse(TouchControlSettings.load(for: package.id).mouseTouchEnabled)
        var savedControls = TouchControlSettings.load(for: package.id)
        savedControls.opacity = 0.35
        savedControls.save(for: package.id)
        XCTAssertEqual(TouchControlSettings.load(for: package.id).opacity, 0.35)
        let session = PlayerSession()
        let scene = try XCTUnwrap(UIApplication.shared.connectedScenes.compactMap { $0 as? UIWindowScene }.first)
        let previousWindow = scene.windows.first(where: { $0.isKeyWindow })
        let window = UIWindow(windowScene: scene)
        let controller = UIViewController()
        window.rootViewController = controller; window.makeKeyAndVisible()
        defer { session.stop(); window.isHidden = true; previousWindow?.makeKey() }
        await session.start(package: package, contentRoot: library.appendingPathComponent(package.id.uuidString).appendingPathComponent("content"))
        let view = try XCTUnwrap(session.webView, session.failure ?? "Missing WebView")
        view.frame = controller.view.bounds; view.autoresizingMask = [.flexibleWidth, .flexibleHeight]
        controller.view.addSubview(view)
        guard try await waitUntil(seconds: 75, condition: { session.isLoaded }) else {
            XCTFail(session.failure ?? "Runtime load timeout: \(session.diagnostics)"); return
        }
        try await assertJS(view, "!new URL(location.href).searchParams.has('mouseTouch')")
        _ = try await view.evaluateJavaScript("document.getElementById('start').click(); true")
        guard try await waitUntil(seconds: 15, condition: { session.diagnostics.contains { $0.contains("SWF: READY") } }) else {
