    private func assertJS(_ view: WKWebView, _ expression: String, file: StaticString = #filePath, line: UInt = #line) async throws {
        let result = try await view.evaluateJavaScript(expression) as? Bool
        XCTAssertEqual(result, true, expression, file: file, line: line)
    }

    private func waitForJS(_ view: WKWebView, _ expression: String, seconds: TimeInterval) async throws -> Bool {
        let deadline = Date().addingTimeInterval(seconds)
        while Date() < deadline {
            if try await view.evaluateJavaScript(expression) as? Bool == true { return true }
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        return try await view.evaluateJavaScript(expression) as? Bool == true
    }

    private func waitUntil(seconds: TimeInterval, condition: () -> Bool) async throws -> Bool {
        let deadline = Date().addingTimeInterval(seconds)
        while Date() < deadline {
            if condition() { return true }
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        return condition()
    }
