/// Actual bundled Ruffle/WASM in WKWebView, with synthetic DOM touch pointers.
/// This does not certify UIKit finger routing or SwiftUI drag recognizers.
@MainActor final class MouseTouchRuntimeTests: XCTestCase {
    func testDefaultOffToggleCornersClicksAndCancellationInBundledRuntime() async throws {
