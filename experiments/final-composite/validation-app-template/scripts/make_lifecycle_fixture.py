#!/usr/bin/env python3
"""Original AVM1 lifecycle-only fixture, based on the passing input-focus fixture.
No vector drawing, scaling, transforms or experimental renderer configuration.
"""
from pathlib import Path
import struct
from make_input_fixture import action, push, integer, variable, call_method, trace, movie

ROOT = Path(__file__).resolve().parents[1]


def member(obj, name):
    return obj + push(name) + action(0x4e)


def increment(name):
    return push(name) + variable(name) + integer(1) + action(0x47) + action(0x1d)


def report(prefix, values):
    code = push(prefix)
    for index, value in enumerate(values):
        if index:
            code += push(':') + action(0x47)
        code += value + action(0x47)
    return code + action(0x26)


def written_save(progress):
    get_save = call_method(variable('SharedObject'), 'getLocal', (push('LifecycleFixture'), push('/')))
    code = push('save') + get_save + action(0x1d)
    data = member(variable('save'), 'data')
    code += push('saveBefore') + member(data, 'progress') + action(0x1d)
    code += report('LIFECYCLE_SAVE_BEFORE:', [variable('saveBefore')])
    code += data + push('progress') + integer(progress) + action(0x4f)
    code += call_method(variable('save'), 'flush') + action(0x17)
    return code


def plain_object(name):
    # Only explicit broadcaster registration must deliver callbacks. A MovieClip
    # property would also receive the stage's clip-event dispatch.
    return push(name) + integer(0) + push('Object') + action(0x40) + action(0x1d)


def object_listener(name, event, body, broadcaster):
    code = body + b'\0'
    function = action(0x9b, b'\0' + struct.pack('<HH', 0, len(code))) + code
    assign = variable(name) + push(event) + function + action(0x4f)
    return assign + call_method(variable(broadcaster), 'addListener', (variable(name),)) + action(0x17)


def generate():
    base = ROOT / 'fixtures/lifecycle'
    (base / 'sub').mkdir(parents=True, exist_ok=True)
    first_key = trace('LIFECYCLE_ROOT_KEY') + action(0x83, b'sub/scene.swf\0_level1\0')
    first_key += call_method(variable('Key'), 'removeListener', (variable('rootListener'),)) + action(0x17)
    root = written_save(410) + plain_object('rootListener')
    root += object_listener('rootListener', 'onKeyDown', first_key, 'Key')
    root += report('LIFECYCLE_ROOT_READY:', [variable('saveBefore')]) + action(0x07)
    child = written_save(420) + plain_object('childListener')
    child += push('keyCount') + integer(0) + action(0x1d)
    child += push('pointerCount') + integer(0) + action(0x1d)
    key_callback = increment('keyCount') + report('LIFECYCLE_CHILD_KEY:', [call_method(variable('Key'), 'getCode'), variable('keyCount')])
    pointer_callback = increment('pointerCount') + report('LIFECYCLE_CHILD_POINTER:', [variable('pointerCount')])
    child += object_listener('childListener', 'onKeyDown', key_callback, 'Key')
    child += object_listener('childListener', 'onMouseDown', pointer_callback, 'Mouse')
    child += trace('LIFECYCLE_CHILD_READY') + action(0x07)
    (base / 'main.swf').write_bytes(movie(root, (22, 44, 88)))
    (base / 'sub/scene.swf').write_bytes(movie(child, (24, 130, 96)))
    (base / 'README.txt').write_text(
        'Original lifecycle-only AVM1 fixture derived from the separately passing input-focus fixture. '
        'No dynamic vector drawing or viewport/rendering experiment. Root explicitly writes/flushed '
        'SharedObject LifecycleFixture progress=410 and first key loads sub/scene.swf into _level1, '
        'then unregisters its plain Object Key listener. Child explicitly writes/flushed progress=420 and uses '
        'a plain Object listener with Key/Mouse counters initialized to zero. No MovieClip callback properties '
        'are registered, avoiding duplicate clip-event plus broadcaster dispatch. LIFECYCLE_CHILD_KEY:<code>:<count> and '
        'LIFECYCLE_CHILD_POINTER:<count> prove live scene continuity. LIFECYCLE_SAVE_BEFORE:<progress> '
        'and LIFECYCLE_ROOT_READY:<progress-before-write> report real SOL before writes, so restart restoration can be checked. '
        'This is not an instant scene save. Generated by scripts/make_lifecycle_fixture.py.\n')
    print('Generated original lifecycle-only fixture')


if __name__ == '__main__':
    generate()
