#!/usr/bin/env python3
"""Original AVM1 targets for viewport scaling, trusted taps and child input tests."""
from pathlib import Path
import struct
from make_input_fixture import action, push, integer, variable, call_method, tag, trace, listener, movie

ROOT = Path(__file__).resolve().parents[1]
POINTS = [('TL', 32, 32), ('TR', 288, 32), ('BL', 32, 208), ('BR', 288, 208), ('C', 160, 120)]


def member(obj, name):
    return obj + push(name) + action(0x4e)


def assign(obj, name, value):
    return obj + push(name) + value + action(0x4f)


def function(body):
    code = body + b'\0'
    return action(0x9b, b'\0' + struct.pack('<HH', 0, len(code))) + code


def conditional(condition, body):
    return condition + action(0x9d, struct.pack('<h', 5)) + action(0x99, struct.pack('<h', len(body))) + body


def report_values(prefix, values):
    code = push(prefix)
    for index, value in enumerate(values):
        if index:
            code += push(':') + action(0x47)
        code += value + action(0x47)
    return code + action(0x26)


def invoke(obj, name, *args):
    return call_method(obj, name, args) + action(0x17)


def frame(child=False):
    root = variable('_root')
    # The fixture itself explicitly writes/flushed SOL. A direct-save UI test
    # must not manufacture storage in JavaScript or call a shutdown to do so.
    save = call_method(variable('SharedObject'), 'getLocal', (push('ViewportFixture'), push('/')))
    code = push('viewportSave') + save + action(0x1d)
    code += assign(member(variable('viewportSave'), 'data'), 'progress', integer(420 if child else 410))
    code += invoke(variable('viewportSave'), 'flush')
    if child:
        code += push('viewportKeyCount') + integer(0) + action(0x1d)
    for depth, (name, x, y) in enumerate(POINTS, 1):
        key = 'target' + name
        code += invoke(root, 'createEmptyMovieClip', push(key), integer(depth))
        clip = member(root, key)
        code += invoke(clip, 'beginFill', integer(0xffae36), integer(100))
        code += invoke(clip, 'moveTo', integer(x - 16), integer(y - 16))
        for px, py in [(x+16, y-16), (x+16, y+16), (x-16, y+16), (x-16, y-16)]:
            code += invoke(clip, 'lineTo', integer(px), integer(py))
        code += invoke(clip, 'endFill')
        coords = [call_method(variable('Math'), 'round', (member(root, axis),)) for axis in ['_xmouse', '_ymouse']]
        code += assign(clip, 'onRelease', function(report_values('VIEWPORT_HIT:' + name + ':', coords)))
    key_code = call_method(variable('Key'), 'getCode')
    if child:
        key_body = push('viewportKeyCount') + variable('viewportKeyCount') + integer(1) + action(0x47) + action(0x1d)
        key_body += report_values('VIEWPORT_CHILD_KEY:', [key_code, variable('viewportKeyCount')])
    else:
        key_body = report_values('VIEWPORT_KEY:', [key_code])
    if not child:
        transition = action(0x83, b'sub/scene.swf\0_level1\0')
        key_body += conditional(key_code + integer(13) + action(0x49), transition)
    no_scale = assign(variable('Stage'), 'scaleMode', push('noScale'))
    no_scale += report_values('VIEWPORT_STAGE:', [member(variable('Stage'), 'width'), member(variable('Stage'), 'height')])
    key_body += conditional(key_code + integer(78) + action(0x49), no_scale)
    code += listener('onKeyDown', key_body, 'Key')
    code += trace('VIEWPORT_CHILD_READY' if child else 'VIEWPORT_ROOT_READY') + action(0x07)
    return code


def generate():
    base = ROOT / 'fixtures/viewport-input'
    (base / 'sub').mkdir(parents=True, exist_ok=True)
    (base / 'main.swf').write_bytes(movie(frame(), (22, 44, 88)))
    (base / 'sub/scene.swf').write_bytes(movie(frame(True), (24, 95, 78)))
    (base / 'README.txt').write_text(
        'Original generated 320x240 AVM1 movie. Five orange 32px targets centered at '
        'TL(32,32), TR(288,32), BL(32,208), BR(288,208), C(160,120). '
        'Real MovieClip.onRelease traces VIEWPORT_HIT:<target>:<rounded stage x>:<rounded stage y>. '
        'Key callback traces VIEWPORT_KEY:<code>; Enter loads sub/scene.swf into _level1 with fresh handlers. '
        'Child keys trace VIEWPORT_CHILD_KEY:<code>:<counter>, proving the same live child survives app switching and direct saves. '
        'N explicitly selects noScale and traces VIEWPORT_STAGE:<width>:<height>, a compatibility negative control. '
        'Each movie explicitly writes and flushes SharedObject ViewportFixture (progress 410/root or 420/child) '
        'so direct-save tests copy genuinely game-written data without ending playback. '
        'No third-party content. Generated by scripts/make_viewport_fixture.py.\n')
    print('Generated original viewport/corner input fixture')


if __name__ == '__main__':
    generate()
